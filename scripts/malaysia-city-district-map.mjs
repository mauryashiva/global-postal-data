async function verifyAllMapped() {
  const pcRes = await fetch('https://raw.githubusercontent.com/heiswayi/malaysia-postcodes/master/data/csv/postcodes.csv');
  const pcCsv = await pcRes.text();
  const pcLines = pcCsv.trim().split('\n').slice(1);

  const dosmRes = await fetch('https://raw.githubusercontent.com/dosm-malaysia/data-open/main/datasets/geodata/state_district.csv');
  const dosmCsv = await dosmRes.text();
  const dosmLines = dosmCsv.trim().split('\n').slice(1);
  const dosmDistrictsByState = {};
  dosmLines.forEach(l => {
    const [state, district] = l.split(',');
    const s = state.trim();
    if (!dosmDistrictsByState[s]) dosmDistrictsByState[s] = new Map();
    dosmDistrictsByState[s].set(district.trim().toLowerCase(), district.trim());
  });

  let fullyResolved = 0;
  const stillUnresolved = [];

  pcLines.forEach(l => {
    const [pc, city, state] = l.trim().split(',');
    const key = `${state}::${city}`;
    if (cityToDistrictMap[key]) {
      fullyResolved++;
    } else {
      const normState = state.replace(/^Wp\s+/i, 'W.P. ');
      const sMap = dosmDistrictsByState[state] || dosmDistrictsByState[normState];
      if (sMap && sMap.has(city.toLowerCase())) {
        fullyResolved++;
      } else {
        stillUnresolved.push({ pc, city, state });
      }
    }
  });

  console.log('Total records:', pcLines.length);
  console.log('Fully resolved to district:', fullyResolved, '/', pcLines.length);
  console.log('Still unresolved count:', stillUnresolved.length);
  if (stillUnresolved.length > 0) {
    const unres = new Set(stillUnresolved.map(u => `${u.state}::${u.city}`));
    console.log('Still unresolved cities:', Array.from(unres));
  }
}
verifyAllMapped();

